export function getQuestionDifficulty(id: string): Difficulty {
  const difficulty = difficulties.find((difficulty) =>
    difficultyGroups[difficulty].includes(id),
  );
  if (!difficulty)
    throw new Error(`Question difficulty is not assigned: ${id}`);
  return difficulty;
}
